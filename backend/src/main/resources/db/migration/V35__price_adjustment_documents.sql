CREATE OR REPLACE FUNCTION pg_temp.price_document_date(value text) RETURNS date LANGUAGE plpgsql AS $$
BEGIN
 IF value IS NULL OR value !~ '^\d{4}-\d{2}-\d{2}$' THEN RETURN NULL; END IF;
 RETURN value::date;
EXCEPTION WHEN OTHERS THEN RETURN NULL;
END $$;
CREATE TEMP TABLE price_document_sources(id bigint,post_id bigint,product_id varchar(255),merchant_id bigint,published boolean,published_at timestamptz,title text,facts jsonb,raw_price jsonb) ON COMMIT DROP;
DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='bb_recommendation_item' AND column_name='offer_start') THEN
  EXECUTE $source$INSERT INTO price_document_sources
   SELECT i.id,i.post_id,i.product_id,p.merchant_id,
    p.published AND i.publication_state='PUBLISHED' AND i.publication_snapshot->>'version'='1',
    i.published_at,p.title,
    CASE WHEN i.publication_state='PUBLISHED' AND i.publication_snapshot IS NOT NULL THEN i.publication_snapshot
    ELSE jsonb_build_object('referencePrice',i.reference_price,'originalPrice',i.original_price,'discountAmount',i.discount_amount,
      'priceUnit',i.price_unit,'offerStart',i.offer_start,'offerEnd',i.offer_end,'itemNumber',i.item_number,'referenceContext',i.reference_context,'offerNotes',i.offer_notes) END,
    jsonb_build_object('amount',i.reference_price,'original',i.original_price,'reduction',i.discount_amount,'unit',i.price_unit,'start',i.offer_start,'end',i.offer_end)
   FROM bb_recommendation_item i JOIN bb_recommendation_post p ON p.id=i.post_id$source$;
 END IF;
END $$;
CREATE TEMP TABLE price_document_prepared ON COMMIT DROP AS
 SELECT s.*,c.channel,c.unit,c.amount,c.original,c.reduction,
 COALESCE(pg_temp.price_document_date(s.facts->>'offerStart'),CASE WHEN s.facts#>>'{referenceContext,activityApplies}'='true'
  AND nullif(btrim(s.facts#>>'{referenceContext,windowEvidence}'),'') IS NOT NULL AND s.facts#>>'{referenceContext,sourceUrl}' LIKE 'https://%'
  THEN pg_temp.price_document_date(s.facts#>>'{referenceContext,activityStart}') END) AS start_day,
 COALESCE(pg_temp.price_document_date(s.facts->>'offerEnd'),CASE WHEN s.facts#>>'{referenceContext,activityApplies}'='true'
  AND nullif(btrim(s.facts#>>'{referenceContext,windowEvidence}'),'') IS NOT NULL AND s.facts#>>'{referenceContext,sourceUrl}' LIKE 'https://%'
  THEN pg_temp.price_document_date(s.facts#>>'{referenceContext,activityEnd}') END) AS end_day
 FROM price_document_sources s CROSS JOIN LATERAL(
  SELECT s.facts#>>'{referenceContext,channel}' AS channel,nullif(btrim(s.facts->>'priceUnit'),'') AS unit,
   (s.facts->>'referencePrice')::numeric AS amount,(s.facts->>'originalPrice')::numeric AS original,(s.facts->>'discountAmount')::numeric AS reduction
 )c
 WHERE s.facts->>'referencePrice' IS NOT NULL OR s.facts->>'originalPrice' IS NOT NULL OR s.facts->>'discountAmount' IS NOT NULL OR s.facts->>'priceUnit' IS NOT NULL OR s.facts->>'offerStart' IS NOT NULL OR s.facts->>'offerEnd' IS NOT NULL
  OR EXISTS(SELECT 1 FROM jsonb_each(s.raw_price) raw WHERE raw.value<>'null'::jsonb);

INSERT INTO bb_product_price_adjustment(merchant_id,channel,currency,document_number,source_key,type,starts_at,ends_at,status,
 source_note,created_by,created_at,updated_by,updated_at,approved_by,approved_at,evidence)
 SELECT merchant_id,COALESCE(channel,'UNRESOLVED'),'JPY','PC-SOURCE-'||id,'recommendation:'||id,
 CASE WHEN amount IS NOT NULL AND COALESCE(original,amount+reduction)>amount THEN 'PROMOTION' WHEN end_day IS NOT NULL THEN 'TEMPORARY' ELSE 'PERMANENT' END,
 start_day::timestamp AT TIME ZONE 'Asia/Tokyo',
 CASE WHEN end_day IS NOT NULL THEN (end_day+1)::timestamp AT TIME ZONE 'Asia/Tokyo' END,
 'DRAFT',left(CASE WHEN COALESCE(original,amount+reduction)>amount THEN '供应商阶段促销' ELSE '供应商报价变更，需复核原因' END||'；来源推荐#'||post_id||'；'||COALESCE(title,'')||'；'||COALESCE(facts->>'offerNotes','来源单据所列商品价格活动'),1000),
 merchant_id,transaction_timestamp(),merchant_id,transaction_timestamp(),NULL,NULL,
 jsonb_build_object('sourceItemId',id,'sourcePostId',post_id,'reviewRequired',true,'sourceSnapshotDigest',md5(facts::text),
  'sourceContext',facts->'referenceContext','sourcePrice',jsonb_build_object('amount',amount,'original',original,'reduction',reduction,'unit',unit,
   'start',facts->>'offerStart','end',facts->>'offerEnd'),'rawItemPrice',raw_price,'sourcePublished',published,'sourceItemNumber',facts->>'itemNumber')
 FROM price_document_prepared ON CONFLICT(source_key) DO NOTHING;
INSERT INTO bb_product_price_adjustment_line(document_id,product_id,amount,before_amount,unit,reference_item_id)
 SELECT d.id,CASE WHEN p.merchant_id=s.merchant_id AND p.deleted_at IS NULL THEN p.id END,s.amount,
 COALESCE(s.original,s.amount+s.reduction),s.unit,s.id
 FROM price_document_prepared s JOIN bb_product_price_adjustment d ON d.source_key='recommendation:'||s.id
 LEFT JOIN bb_product p ON p.id=s.product_id
 WHERE NOT EXISTS(SELECT 1 FROM bb_product_price_adjustment_line l WHERE l.document_id=d.id AND l.reference_item_id=s.id);
-- Transfer only fully evidenced, already published, unambiguous promotions into approved documents.
UPDATE bb_product_price_adjustment d SET status='APPROVED',approved_by=d.merchant_id,
 approved_at=COALESCE(s.published_at,d.created_at),evidence=d.evidence||'{"reviewRequired":false}'
 FROM price_document_prepared s JOIN bb_product p ON p.id=s.product_id
 WHERE d.source_key='recommendation:'||s.id AND s.published AND d.type='PROMOTION'
  AND s.start_day IS NOT NULL AND s.end_day>=s.start_day AND s.unit IS NOT NULL
  AND s.channel IN ('COSTCO_WAREHOUSE','COSTCO_ONLINE') AND s.amount>0
  AND COALESCE(s.original,s.amount+s.reduction)>s.amount
  AND p.merchant_id=s.merchant_id AND p.deleted_at IS NULL AND p.item_number=s.facts->>'itemNumber'
  AND NOT EXISTS(SELECT 1 FROM price_document_prepared other WHERE other.id<>s.id AND other.product_id=s.product_id
   AND other.merchant_id=s.merchant_id AND other.channel=s.channel AND other.unit=s.unit
   AND other.start_day<=s.end_day AND s.start_day<=other.end_day);

