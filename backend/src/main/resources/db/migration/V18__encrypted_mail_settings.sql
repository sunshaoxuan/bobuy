-- Additive only. No credentials or enabled configuration are seeded.
CREATE TABLE bb_mail_settings (
 id integer PRIMARY KEY CHECK (id = 1),
 version bigint NOT NULL DEFAULT 0,
 enabled boolean NOT NULL DEFAULT false,
 host varchar(253) NOT NULL, port integer NOT NULL,
 tls_mode varchar(20) NOT NULL,
 username varchar(254) NOT NULL, from_address varchar(254) NOT NULL,
 reply_to varchar(254) NOT NULL,
 encrypted_password text,
 key_id varchar(40),
 updated_by bigint NOT NULL, updated_at timestamptz NOT NULL
);
CREATE TABLE bb_mail_settings_event (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id bigint NOT NULL, occurred_at timestamptz NOT NULL,
 event_type varchar(30) NOT NULL, settings_version bigint NOT NULL
);
