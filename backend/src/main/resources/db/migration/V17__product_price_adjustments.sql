CREATE TABLE bb_product_price_adjustment (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version bigint NOT NULL DEFAULT 0,
 merchant_id bigint NOT NULL,
 product_id varchar(255) NOT NULL REFERENCES bb_product(id),
 channel varchar(40) NOT NULL,
 currency varchar(3) NOT NULL,
 amount numeric(18,4) NOT NULL CHECK (amount > 0),
 unit varchar(80),
 starts_at timestamptz NOT NULL,
 ends_at timestamptz NOT NULL,
 status varchar(20) NOT NULL CHECK (status IN ('DRAFT','APPROVED','CANCELLED')),
 source_note varchar(1000) NOT NULL,
 created_by bigint NOT NULL, created_at timestamptz NOT NULL,
 updated_by bigint NOT NULL, updated_at timestamptz NOT NULL,
 approved_by bigint, approved_at timestamptz,
 cancelled_by bigint, cancelled_at timestamptz,
 CHECK (starts_at < ends_at)
);
CREATE INDEX bb_price_adjustment_scope ON bb_product_price_adjustment(product_id,channel,currency,status,starts_at,ends_at);
